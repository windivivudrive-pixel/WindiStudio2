export type CaptionWord = {text: string; startMs: number; endMs: number};
export type CaptionGroup = {text: string; startMs: number; endMs: number; words: CaptionWord[]};
export type LayoutValues = {x?: number; y?: number; width?: number; height?: number; fontSize?: number; lineHeight?: number; color?: string; textAlign?: 'left' | 'center' | 'right'; wrap?: boolean};
export type LayoutMap = Record<string, LayoutValues>;
export type WindowTransform = {x?: number; y?: number; scale?: number};
export type WindowMedia = {kind: 'image' | 'video'; src: string; trimBefore: number; fit: 'cover' | 'contain'; zoom: number; x: number; y: number; volume: number};
export type MediaClip = {id: string; startFrame: number; endFrame: number; media: WindowMedia};
export type TimelineItemKey = `caption:${number}` | `media:${string}` | 'music';
export type LayoutSpec = {id: string; label: string; mode?: 'text' | 'scale' | 'caption'; x: number; y: number; width: number; height: number; fontSize?: number};
export type EditorBeat = {
  id: string | number;
  index?: number;
  name?: string;
  startFrame: number;
  endFrame: number;
  headline: string;
  spokenPill: string;
  category: string;
  windowTitle?: string;
  accentColor?: string;
  layout?: LayoutMap;
  windowTransform?: WindowTransform;
  transition?: {type: 'none' | 'fade' | 'scan'; durationInFrames: number};
  media?: WindowMedia;
};
export type EditorDocument = {
  schemaVersion: 1;
  episodeId: string;
  revision: number;
  fps: number;
  totalFrames: number;
  beats: EditorBeat[];
  captions: CaptionGroup[];
  layout?: LayoutMap;
  windowTransform?: WindowTransform;
  mediaClips?: MediaClip[];
  audio: {voice: string; music: string; voiceVolume: number; musicVolume: number; sfxVolume: number; musicTrimBefore?: number; musicOffsetFrames?: number; musicFadeInFrames?: number; musicFadeOutFrames?: number};
};
export type EditorProps = {editor?: EditorDocument};
